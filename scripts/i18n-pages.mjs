// Generates the English and Spanish entry pages from the Portuguese sources,
// and copies the locale files next to the apps page (its own deploy root).
// Run by hand after editing a page or a locale file:  node scripts/i18n-pages.mjs
// No bundler, no framework: plain string replacement over our own markup.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname } from 'node:path';

const root = new URL('../', import.meta.url).pathname;
const PAGES = ['index.html', 'como-funciona/index.html', 'precos/index.html', 'mcp/index.html'];
const LOCALES = ['en', 'es'];
const SITE = 'https://alphatester.app/';

const read = (p) => readFileSync(root + p, 'utf8');
const dict = (loc) => JSON.parse(read(`assets/i18n/${loc}.json`));
const get = (d, key) => key.split('.').reduce((v, k) => (v == null ? v : v[k]), d);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escAttr = (s) => esc(s).replace(/"/g, '&quot;');
const HREF = {
  home: (l) => `/${l}/`, como: (l) => `/${l}/como-funciona/`, precos: (l) => `/${l}/precos/`,
  apps: (l) => `https://apps.alphatester.app/?lang=${l}`
};

function value(d, key) {
  const v = get(d, key);
  if (v === undefined) throw new Error(`missing key ${key}`);
  return v;
}

function localize(src, loc) {
  const d = dict(loc);
  let out = src;
  // text-only elements
  out = out.replace(/(<([a-z0-9]+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>)([^<]*)(<\/\2>)/g,
    (m, open, tag, key, _t, close) => open + esc(value(d, key)) + close);
  // trusted markup from our own files
  out = out.replace(/(<([a-z0-9]+)\b[^>]*\sdata-i18n-html="([^"]+)"[^>]*>)([\s\S]*?)(<\/\2>)/g,
    (m, open, tag, key, _t, close) => open + value(d, key) + close);
  // attributes, then locale-aware links
  out = out.replace(/<[a-z][^>]*\sdata-i18n-attr="([^"]+)"[^>]*>/g, (tag, spec) => {
    for (const pair of spec.split(';')) {
      const [attr, key] = pair.split(':').map((x) => x.trim());
      tag = tag.replace(new RegExp(`(\\s${attr}=")[^"]*(")`), `$1${escAttr(value(d, key))}$2`);
    }
    return tag;
  });
  out = out.replace(/<a\b[^>]*\sdata-href="([a-z]+)"[^>]*>/g,
    (tag, name) => tag.replace(/(\shref=")[^"]*(")/, `$1${HREF[name](loc)}$2`));
  out = out.replace(/(<[^>]*\sdata-canonical="([^"]*)"[^>]*>)/g,
    (tag, _t, path) => tag.replace(/((?:href|content)=")[^"]*(")/, `$1${SITE}${loc}/${path}$2`));
  out = out.replace(/data-lang-btn="([^"]+)"([^>]*)aria-pressed="(true|false)"/g,
    (m, l, mid) => `data-lang-btn="${l}"${mid}aria-pressed="${l === loc ? 'true' : 'false'}"`);
  out = out.replace('<html lang="pt-BR">', `<html lang="${loc}" data-locale-preset="${loc}">`);
  return out.replace('<head>\n', '<head>\n<!-- generated by scripts/i18n-pages.mjs from the pt-BR page; edit that page and rerun -->\n');
}

for (const page of PAGES) {
  let src;
  try { src = read(page); } catch { continue; }
  for (const loc of LOCALES) {
    const target = `${root}${loc}/${page}`;
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, localize(src, loc));
    console.log(`wrote ${loc}/${page}`);
  }
}

// the apps page is served from apps/ as its own site root: give it the runtime and the locale files
mkdirSync(root + 'apps/i18n', { recursive: true });
copyFileSync(root + 'assets/i18n.js', root + 'apps/i18n.js');
for (const loc of ['pt-BR', 'en', 'es']) copyFileSync(root + `assets/i18n/${loc}.json`, root + `apps/i18n/${loc}.json`);
console.log('copied i18n runtime and locale files to apps/');
